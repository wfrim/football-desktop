#!/usr/bin/env node
/*
 * Bundles the formations + plays listed in src/data/manifest.json into
 * src/data/plays.bundle.js so the wallpaper works from file:// (Plash local
 * file) where fetch() of local JSON is blocked.
 *
 *   node tools/bundle-data.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(root, 'src', 'data');
const read = (f) => JSON.parse(readFileSync(join(dataDir, f), 'utf8'));
const manifest = read('manifest.json');

const formations = (manifest.formations || []).map(read);
const plays = [];
for (const f of manifest.plays || []) {
  const json = read(f);
  plays.push(...(Array.isArray(json) ? json : [json]));
}

const concepts = (manifest.concepts || []).map(read);

writeFileSync(
  join(dataDir, 'plays.bundle.js'),
  '/* GENERATED by tools/bundle-data.mjs from src/data/manifest.json. Do not edit by hand. */\n' +
    `FD.Data.register(${JSON.stringify({ formations, concepts, plays })});\n`
);
console.log(`Bundled ${formations.length} formation(s), ${concepts.length} concept(s), ${plays.length} play file(s) → src/data/plays.bundle.js`);
